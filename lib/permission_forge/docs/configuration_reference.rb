# frozen_string_literal: true

require 'yaml'

module PermissionForge
  # Generators of the gem's own documentation (development only; nothing here
  # runs in a host application).
  #
  # @api private
  module Docs
    # The "Option reference" of docs/configuration.md, rendered from the code:
    # Admin::SettingsCatalog::DEFINITIONS give the sections, the options and
    # their order (the admin's Settings page), Configuration.new the defaults,
    # Configuration::StrategyValues::ALLOWED what a strategy option takes, and
    # the en locale the section titles and the first text of an option that
    # has none yet. Every other public writer of Configuration follows under
    # "Other options". The prose under each heading is kept from the document
    # as it stands; the headings, their order and the `**Default:**` lines are
    # regenerated (`bundle exec rake docs:configuration`;
    # docs/configuration_reference_test.rb fails while the file is stale).
    #
    # @api private
    class ConfigurationReference
      START_MARK = '<!-- option-reference:start -->'
      END_MARK = '<!-- option-reference:end -->'
      NOTE = "<!-- Generated by `bundle exec rake docs:configuration` from SettingsCatalog and Configuration.new.\n     " \
             "Edit the text under a heading here (or settings.items.<option> in the en locale for a new option):\n     " \
             'the headings, their order and the **Default:** lines are regenerated. -->'
      GENERATED_LINE = /\A\*\*Default:\*\*/
      OTHER_SECTION = 'Other options'
      PLACEHOLDER = '_Describe this option._'
      LOCALE = File.expand_path('../../../config/locales/permission_forge.en.yml', __dir__)

      # One `###` section of the reference: its title and the options under it.
      Section = Struct.new(:title, :keys) do
        def text(reference, existing)
          intro = existing.section(title)
          "### #{title}\n\n#{"#{intro}\n\n" unless intro.empty?}#{keys.map { |key| reference.entry(key, existing) }.join}"
        end
      end

      attr_reader :document

      # @param document [String] docs/configuration.md as it stands
      def initialize(document:, configuration: Configuration.new, definitions: Admin::SettingsCatalog::DEFINITIONS,
                     locale: LOCALE)
        @document = document
        @configuration = configuration
        @definitions = definitions
        @locale = YAML.load_file(locale).dig('en', 'permission_forge', 'settings')
        @values = Admin::SettingsValues.new
      end

      # The document with its reference regenerated.
      def render
        before, region, after = split
        existing = ExistingProse.new(region)
        "#{before}#{START_MARK}\n#{NOTE}\n\n#{sections.map { |section| section.text(self, existing) }.join}#{END_MARK}#{after}"
      end

      def stale? = render != document

      # The option headings the reference holds, in order.
      def keys = sections.flat_map(&:keys)

      # One option's entry: heading, the generated default line, the text.
      def entry(key, existing)
        "#### #{key}\n\n#{default_line(key)}\n\n#{option_text(key, existing)}\n\n"
      end

      private

      # The document before the start mark, the region between the marks, the rest.
      def split
        start = document.index(START_MARK) or raise ArgumentError, "#{START_MARK} not found in the document"
        stop = document.index(END_MARK, start) or raise ArgumentError, "#{END_MARK} not found in the document"
        [document[0...start], document[(start + START_MARK.length)...stop], document[(stop + END_MARK.length)..]]
      end

      def sections
        @sections ||= begin
          by_section = @definitions.group_by(&:section)
          catalog = Admin::SettingsCatalog::SECTIONS.map { |key| Section.new(@locale['sections'].fetch(key), by_section.fetch(key, []).map(&:key)) }
          others = writers - @definitions.map(&:key)
          others.empty? ? catalog : catalog << Section.new(OTHER_SECTION, others)
        end
      end

      def writers
        (@configuration.class.public_instance_methods - Object.public_instance_methods)
          .grep(/\A\w+=\z/).map { |name| name.to_s.chomp('=') }.sort
      end

      # The text under an option: what the document says, else the Settings page's name and description.
      def option_text(key, existing)
        text = existing.option(key)
        return text unless text.empty?

        name, desc = @locale['items'].fetch(key, {}).values_at('name', 'desc')
        name ? "**#{name.sub(/\.\z/, '')}.** #{desc}" : PLACEHOLDER
      end

      def default_line(key)
        takes = takes_text(key)
        "**Default:** #{default_text(key)}#{" Takes #{takes}." if takes}"
      end

      def takes_text(key)
        allowed = Configuration::StrategyValues::ALLOWED[key.to_sym] or return
        values = allowed.map { |value| "`#{value.inspect}`" }
        list = values.size > 1 ? "#{values[0..-2].join(', ')} or #{values.last}" : values.first
        "#{list} (or its String)#{', or nil' if Configuration::StrategyValues::BLANK_ALLOWED.include?(key.to_sym)}"
      end

      def default_text(key)
        value = @configuration.public_send(key)
        case value
        when nil then nil_text(definition(key))
        when Proc then "the gem's own lambda"
        when Hash then hash_text(key, value)
        else "`#{@values.ruby_literal(value)}`"
        end
      end

      def definition(key) = @definitions.find { |candidate| candidate.key == key }

      def nil_text(definition)
        case definition&.nil_label
        when :default then '`nil` (the built-in behaviour)'
        when :disabled then '`nil` (off)'
        else '`nil`'
        end
      end

      def hash_text(key, value)
        return '`{}`' if value.empty?
        return '`PermissionForge::Configuration::DEFAULT_GDPR_FIELD_PATTERNS`' if value == Configuration::DEFAULT_GDPR_FIELD_PATTERNS

        pairs = @values.normalize(definition(key) || Admin::SettingsCatalog.d(key, 'other', :map), value)
        pairs.map { |pattern, target| "`#{pattern}` (#{target})" }.join(', ')
      end

      # What the document says under each heading of the region: the section
      # intros (keyed by title) and the option texts (keyed by option), the
      # generated lines and the note left out.
      class ExistingProse
        def initialize(region)
          @sections = Hash.new { |hash, key| hash[key] = +'' }
          @options = Hash.new { |hash, key| hash[key] = +'' }
          collect(region.sub(/\A\s*<!--.*?-->/m, ''))
        end

        def section(title) = @sections[title].strip
        def option(key) = @options[key].strip

        private

        def collect(region)
          bucket = +''
          region.each_line do |line|
            case line.chomp
            when /\A### (.+)\z/ then bucket = @sections[Regexp.last_match(1).strip]
            when /\A#### (\w+)\s*\z/ then bucket = @options[Regexp.last_match(1)]
            when ConfigurationReference::GENERATED_LINE then next
            else bucket << line
            end
          end
        end
      end
    end
  end
end
